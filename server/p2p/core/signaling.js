// Direct P2P File Transfer - signaling hub (portable: no Node or browser APIs beyond setTimeout / optional crypto).
// Ported from the standalone app's server.ts (WebSocket signaling). The hub only brokers WebRTC setup between two peers:
// SDP offers/answers and ICE candidates. File bytes NEVER pass through it (they travel over the peers' direct DataChannel),
// and there is no TURN/relay fallback, so a transfer needs a network path between the two devices.
//
// Differences from the standalone server (all deliberate; covered by tests/p2p-hub.test.html):
//  * Every session must authenticate first ({type:'auth', token}); the Node wrapper supplies verifyToken (Supabase).
//  * Room codes are generated by the server (8 chars, crypto-random, unambiguous alphabet) via {type:'create'}; {type:'join'} only
//    joins an EXISTING room (the original created a room for any 3+ character string, so codes could be guessed and squatted).
//  * Rooms expire (idle 30 min, absolute 2 h); join failures, room creation and message rates are limited per session / user.
//  * Only offer / answer / ice are relayed, re-serialised with whitelisted fields (the original forwarded any raw message).
//  * "Nearby devices" discovery (peers grouped by IP) is OFF unless config.nearby is true: it shows other users' pairing
//    codes to everyone sharing an IP address, which is a privacy leak behind NAT or a proxy.
//  * No unauthenticated HTTP room-status endpoint (it allowed enumerating rooms).

export const CODE_ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'; // no 0 O 1 I L
export const CODE_LENGTH = 8;
const RELAY_TYPES = new Set(['offer', 'answer', 'ice']);
const PEER_ID_RE = /^[A-Za-z0-9_-]{4,32}$/;

export const DEFAULT_CONFIG = {
  nearby: false,
  maxPeersPerRoom: 2,
  maxRoomsPerUser: 3,
  roomIdleMs: 30 * 60 * 1000,
  roomMaxAgeMs: 2 * 60 * 60 * 1000,
  graceMs: 5000,
  authTimeoutMs: 8000,
  maxMessageChars: 65536,
  createLimit: { max: 10, windowMs: 10 * 60 * 1000 },
  joinFailLimit: { max: 10, windowMs: 60 * 1000 },
  messageLimit: { max: 200, windowMs: 10 * 1000 },
};

export function normalizeRoomCode(input) {
  return String(input == null ? '' : input).toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 32);
}

function defaultRandomBytes(n) {
  const c = globalThis.crypto;
  if (!c || typeof c.getRandomValues !== 'function') throw new Error('No secure random source available');
  return c.getRandomValues(new Uint8Array(n));
}

class Window {
  constructor(max, windowMs) { this.max = max; this.windowMs = windowMs; this.hits = []; }
  /** true when the action is allowed (and counted) */
  take(now) {
    this.hits = this.hits.filter((t) => now - t < this.windowMs);
    if (this.hits.length >= this.max) return false;
    this.hits.push(now);
    return true;
  }
}

export class SignalingHub {
  /**
   * @param {{ verifyToken: (token:string)=>Promise<{userId:string}|null>, now?:()=>number, randomBytes?:(n:number)=>Uint8Array,
   *           config?:object, logger?:{warn:Function} }} opts
   */
  constructor({ verifyToken, now, randomBytes, config, logger } = {}) {
    if (typeof verifyToken !== 'function') throw new Error('SignalingHub: verifyToken is required');
    this.verifyToken = verifyToken;
    this.now = now || (() => Date.now());
    this.randomBytes = randomBytes || defaultRandomBytes;
    this.config = { ...DEFAULT_CONFIG, ...(config || {}) };
    this.logger = logger || console;
    this.rooms = new Map(); // code -> { code, createdAt, lastActivity, ownerUserId, peers: Map<session, true> }
    this.sessions = new Set();
    this.networkGroups = new Map(); // networkKey -> Set<session>   (only used when config.nearby)
    this.userLimits = new Map(); // userId -> { create: Window }
  }

  /** @param {{send:(s:string)=>void, close:(code?:number,reason?:string)=>void, meta?:{networkKey?:string}}} conn */
  attach(conn) {
    const session = new Session(this, conn);
    this.sessions.add(session);
    return session;
  }

  generateRoomCode() {
    for (let attempt = 0; attempt < 20; attempt++) {
      const bytes = this.randomBytes(CODE_LENGTH * 2);
      let code = '';
      for (let i = 0; i < bytes.length && code.length < CODE_LENGTH; i++) {
        // rejection sampling keeps the distribution uniform over the 31 symbols
        if (bytes[i] < 248) code += CODE_ALPHABET[bytes[i] % CODE_ALPHABET.length];
      }
      if (code.length === CODE_LENGTH && !this.rooms.has(code)) return code;
    }
    throw new Error('Could not allocate a room code');
  }

  roomsOwnedBy(userId) {
    let n = 0;
    for (const r of this.rooms.values()) if (r.ownerUserId === userId) n++;
    return n;
  }

  userWindow(userId, name, limit) {
    let entry = this.userLimits.get(userId);
    if (!entry) { entry = {}; this.userLimits.set(userId, entry); }
    if (!entry[name]) entry[name] = new Window(limit.max, limit.windowMs);
    return entry[name];
  }

  /** Remove expired rooms; call periodically (the Node wrapper does it every minute). */
  sweep() {
    const now = this.now();
    for (const [code, room] of this.rooms) {
      const tooOld = now - room.createdAt > this.config.roomMaxAgeMs;
      const idle = now - room.lastActivity > this.config.roomIdleMs;
      if (tooOld || idle) {
        for (const s of room.peers.keys()) {
          s.send({ type: 'error', code: 'room-expired', message: 'This transfer room has expired. Create a new one.' });
          s.room = null;
        }
        this.rooms.delete(code);
      }
    }
    if (this.userLimits.size > 5000) this.userLimits.clear();
  }

  stats() { return { rooms: this.rooms.size, sessions: this.sessions.size }; }
}

class Session {
  constructor(hub, conn) {
    this.hub = hub;
    this.conn = conn;
    this.userId = null;
    this.authed = false;
    this.authPending = false;
    this.peerId = Math.random().toString(36).slice(2, 9);
    this.room = null; // room object
    this.closed = false;
    this.networkKey = (conn.meta && conn.meta.networkKey) || null;
    this.presence = null;
    this.msgWindow = new Window(hub.config.messageLimit.max, hub.config.messageLimit.windowMs);
    this.joinFailWindow = new Window(hub.config.joinFailLimit.max, hub.config.joinFailLimit.windowMs);
    this.authTimer = setTimeout(() => {
      if (!this.authed && !this.closed) {
        this.send({ type: 'error', code: 'auth-timeout', message: 'Authentication timed out.' });
        this.terminate(4001, 'auth-timeout');
      }
    }, hub.config.authTimeoutMs);
  }

  send(obj) {
    if (this.closed) return;
    try { this.conn.send(JSON.stringify(obj)); } catch (_) { /* socket already gone */ }
  }

  terminate(code, reason) {
    try { this.conn.close(code, reason); } catch (_) { /* ignore */ }
    this.onClose();
  }

  async onMessage(raw) {
    if (this.closed) return;
    const text = typeof raw === 'string' ? raw : String(raw);
    if (text.length > this.hub.config.maxMessageChars) {
      this.send({ type: 'error', code: 'too-large', message: 'Message too large.' });
      return;
    }
    if (!this.msgWindow.take(this.hub.now())) {
      this.send({ type: 'error', code: 'rate-limit', message: 'Too many messages. Slow down.' });
      this.terminate(4008, 'rate-limit');
      return;
    }
    let msg;
    try { msg = JSON.parse(text); } catch (_) { return; }
    if (!msg || typeof msg !== 'object' || typeof msg.type !== 'string') return;

    if (!this.authed) {
      if (msg.type !== 'auth') {
        this.send({ type: 'error', code: 'auth-required', message: 'Sign in required.' });
        return;
      }
      await this.handleAuth(msg);
      return;
    }

    switch (msg.type) {
      case 'heartbeat':
      case 'ping':
        this.send({ type: 'pong', timestamp: this.hub.now() });
        return;
      case 'create': this.handleCreate(msg); return;
      case 'join': this.handleJoin(msg); return;
      case 'leave': this.leaveRoom(true); return;
      case 'presence': this.handlePresence(msg); return;
      case 'direct-connect-invite': this.handleInvite(msg); return;
      default:
        if (RELAY_TYPES.has(msg.type)) this.relay(msg);
    }
  }

  async handleAuth(msg) {
    if (this.authPending) return;
    this.authPending = true;
    let result = null;
    try {
      result = typeof msg.token === 'string' && msg.token ? await this.hub.verifyToken(msg.token) : null;
    } catch (err) {
      this.authPending = false;
      this.send({ type: 'error', code: 'auth-unavailable', message: 'Could not verify your session. Try again shortly.' });
      this.terminate(4003, 'auth-unavailable');
      return;
    }
    this.authPending = false;
    if (this.closed) return;
    if (!result || !result.userId) {
      this.send({ type: 'error', code: 'auth-failed', message: 'Invalid or expired session. Sign in again.' });
      this.terminate(4001, 'auth-failed');
      return;
    }
    this.authed = true;
    this.userId = result.userId;
    clearTimeout(this.authTimer);
    if (typeof msg.peerId === 'string' && PEER_ID_RE.test(msg.peerId)) this.peerId = msg.peerId;
    this.send({
      type: 'welcome',
      peerId: this.peerId,
      nearby: !!this.hub.config.nearby,
      codeLength: CODE_LENGTH,
      limits: { roomIdleMinutes: Math.round(this.hub.config.roomIdleMs / 60000), roomMaxHours: Math.round(this.hub.config.roomMaxAgeMs / 3600000) },
    });
  }

  adoptPeerId(msg) {
    if (typeof msg.peerId === 'string' && PEER_ID_RE.test(msg.peerId)) this.peerId = msg.peerId;
  }

  handleCreate(msg) {
    this.adoptPeerId(msg);
    const hub = this.hub;
    if (!hub.userWindow(this.userId, 'create', hub.config.createLimit).take(hub.now())) {
      this.send({ type: 'error', code: 'rate-limit', message: 'Too many rooms created. Try again in a few minutes.' });
      return;
    }
    this.leaveRoom(true);
    if (hub.roomsOwnedBy(this.userId) >= hub.config.maxRoomsPerUser) {
      this.send({ type: 'error', code: 'too-many-rooms', message: 'You already have the maximum number of open transfer rooms.' });
      return;
    }
    const code = hub.generateRoomCode();
    const now = hub.now();
    const room = { code, createdAt: now, lastActivity: now, ownerUserId: this.userId, peers: new Map() };
    hub.rooms.set(code, room);
    this.enterRoom(room, true);
  }

  handleJoin(msg) {
    this.adoptPeerId(msg);
    const hub = this.hub;
    const code = normalizeRoomCode(msg.room);
    const fail = (errCode, message) => {
      if (!this.joinFailWindow.take(hub.now())) {
        this.send({ type: 'error', code: 'rate-limit', message: 'Too many failed attempts. Wait a minute and try again.' });
        this.terminate(4008, 'rate-limit');
        return;
      }
      this.send({ type: 'error', code: errCode, message });
    };
    if (code.length !== CODE_LENGTH) return fail('bad-code', `A room code has ${CODE_LENGTH} characters.`);
    const room = hub.rooms.get(code);
    if (!room) return fail('room-not-found', 'No transfer room with that code. Check it, or ask the sender for a new one.');
    if (this.room === room) return; // already there
    // Reconnection of the same peer id: evict the stale socket
    for (const other of [...room.peers.keys()]) {
      if (other !== this && other.peerId === this.peerId) {
        room.peers.delete(other);
        other.room = null;
        try { other.conn.close(4000, 'replaced'); } catch (_) { /* ignore */ }
        other.onClose();
      }
    }
    if (room.peers.size >= hub.config.maxPeersPerRoom) return fail('room-full', 'Room is full (max 2 devices per transfer session).');
    this.leaveRoom(true);
    this.enterRoom(room, false);
  }

  enterRoom(room, created) {
    room.peers.set(this, true);
    room.lastActivity = this.hub.now();
    this.room = room;
    this.send({ type: 'joined', room: room.code, peerId: this.peerId, isInitiator: room.peers.size === 1, peerCount: room.peers.size, created: !!created });
    for (const other of room.peers.keys()) {
      if (other !== this) other.send({ type: 'peer-joined', peerId: this.peerId, peerCount: room.peers.size });
    }
  }

  leaveRoom(notify) {
    const room = this.room;
    if (!room) return;
    this.room = null;
    room.peers.delete(this);
    if (notify) for (const other of room.peers.keys()) other.send({ type: 'peer-left', peerId: this.peerId });
    if (room.peers.size === 0) this.hub.rooms.delete(room.code);
  }

  relay(msg) {
    const room = this.room;
    if (!room) return;
    room.lastActivity = this.hub.now();
    const out = { type: msg.type };
    if (msg.type === 'ice') out.candidate = msg.candidate; else out.sdp = msg.sdp;
    for (const other of room.peers.keys()) if (other !== this) other.send(out);
  }

  // ---- optional nearby discovery (config.nearby) ----
  handlePresence(msg) {
    if (!this.hub.config.nearby || !this.networkKey) return;
    this.adoptPeerId(msg);
    this.presence = { device: msg.device && typeof msg.device === 'object' ? msg.device : {}, code: typeof msg.code === 'string' ? normalizeRoomCode(msg.code) : '' };
    let group = this.hub.networkGroups.get(this.networkKey);
    if (!group) { group = new Set(); this.hub.networkGroups.set(this.networkKey, group); }
    group.add(this);
    this.broadcastNearby();
  }

  broadcastNearby() {
    const group = this.hub.networkGroups.get(this.networkKey);
    if (!group) return;
    for (const target of group) {
      const devices = [...group].filter((s) => s !== target && s.presence).map((s) => ({ peerId: s.peerId, code: s.presence.code, device: s.presence.device, isSelf: false }));
      target.send({ type: 'nearby-devices', networkGroup: this.networkKey, devices });
    }
  }

  handleInvite(msg) {
    if (!this.hub.config.nearby || !this.networkKey) return;
    const group = this.hub.networkGroups.get(this.networkKey);
    if (!group) return;
    for (const target of group) {
      if (target.peerId === msg.targetPeerId) {
        target.send({ type: 'incoming-connect-request', fromPeerId: this.peerId, fromDevice: msg.fromDevice && typeof msg.fromDevice === 'object' ? msg.fromDevice : {}, roomCode: normalizeRoomCode(msg.roomCode) });
        break;
      }
    }
  }

  onClose() {
    if (this.closed) return;
    this.closed = true;
    clearTimeout(this.authTimer);
    this.hub.sessions.delete(this);
    if (this.networkKey && this.hub.networkGroups.has(this.networkKey)) {
      const group = this.hub.networkGroups.get(this.networkKey);
      group.delete(this);
      if (group.size === 0) this.hub.networkGroups.delete(this.networkKey); else this.broadcastNearby();
    }
    const room = this.room;
    if (!room) return;
    this.room = null;
    room.peers.delete(this);
    const peerId = this.peerId;
    const hub = this.hub;
    // Grace period: let the client reconnect before announcing that the peer left.
    setTimeout(() => {
      const current = hub.rooms.get(room.code);
      if (!current || current !== room) return;
      let reconnected = false;
      for (const other of room.peers.keys()) if (other.peerId === peerId) reconnected = true;
      if (!reconnected) for (const other of room.peers.keys()) other.send({ type: 'peer-left', peerId });
      if (room.peers.size === 0) hub.rooms.delete(room.code);
    }, hub.config.graceMs);
  }
}
